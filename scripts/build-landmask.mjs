// Generates src/lib/landmask.ts — a 1° equirectangular land/ocean bitmask used to place
// the illustrative globe dots (3D globe + 2D fallback map).
// Source data: Natural Earth 1:110m land (public domain) via the `world-atlas` npm package.
// Run with: npm run landmask
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoBounds, geoContains } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

// Split into individual polygons with bounding boxes so each point only tests nearby shapes.
const polygons = [];
for (const f of land.features) {
  const geom = f.geometry;
  const list = geom.type === 'MultiPolygon' ? geom.coordinates : [geom.coordinates];
  for (const coords of list) {
    const poly = { type: 'Feature', geometry: { type: 'Polygon', coordinates: coords } };
    const [[x0, y0], [x1, y1]] = geoBounds(poly);
    polygons.push({ poly, x0, y0, x1, y1, wraps: x0 > x1 });
  }
}

const W = 360;
const H = 180;
const bytes = new Uint8Array(Math.ceil((W * H) / 8));
let landCount = 0;
for (let row = 0; row < H; row++) {
  const lat = 89.5 - row;
  for (let col = 0; col < W; col++) {
    const lon = -179.5 + col;
    let hit = false;
    for (const p of polygons) {
      if (lat < p.y0 || lat > p.y1) continue;
      if (!p.wraps && (lon < p.x0 || lon > p.x1)) continue;
      if (geoContains(p.poly, [lon, lat])) {
        hit = true;
        break;
      }
    }
    if (hit) {
      const i = row * W + col;
      bytes[i >> 3] |= 1 << (i & 7);
      landCount++;
    }
  }
}

const b64 = Buffer.from(bytes).toString('base64');
const out = `// AUTO-GENERATED by scripts/build-landmask.mjs — do not edit by hand.
// 1° equirectangular land mask (${W}x${H}, row 0 = 89.5°N, col 0 = 179.5°W).
// Source: Natural Earth 1:110m land (public domain), via the world-atlas package.
// Land cells: ${landCount} of ${W * H}.
export const LANDMASK_W = ${W};
export const LANDMASK_H = ${H};
export const LANDMASK_B64 =
  '${b64}';
`;
writeFileSync(new URL('../src/lib/landmask.ts', import.meta.url), out);
console.log(`landmask written: ${landCount} land cells, ${b64.length} base64 chars`);
