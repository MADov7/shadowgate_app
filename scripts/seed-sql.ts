// Writes supabase/seed.sql — the 12 products as an idempotent INSERT … ON CONFLICT (slug) DO UPDATE.
//   npm run seed:sql
import { writeFileSync } from 'node:fs';
import { productRows } from './seed-rows';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const rows = productRows();
const cols = Object.keys(rows[0]);
const values = rows.map((r) => `  (${cols.map((c) => q((r as Record<string, unknown>)[c])).join(', ')})`).join(',\n');
const updates = cols.filter((c) => c !== 'slug').map((c) => `  ${c} = excluded.${c}`).join(',\n');

const sql = `-- SHADOW GATE — product seed for public.products (${rows.length} services, English + Arabic).
-- Generated by \`npm run seed:sql\`. Safe to run again: rows are matched by slug and updated in place.
insert into public.products (${cols.join(', ')}) values
${values}
on conflict (slug) do update set
${updates};
`;

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql, 'utf8');
console.log(`wrote supabase/seed.sql (${rows.length} products)`);
