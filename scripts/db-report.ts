// Read-only report of what is stored in MongoDB Atlas (for the classwork evidence). Never prints a full password
// hash, a password or the connection string.
//   npm run db:report            → text report
//   npm run db:report -- --html  → also writes db-report.html (a database view for the screenshot)
import { writeFileSync } from 'node:fs';
import mongoose from 'mongoose';
import { connectDB } from '../lib/db';
import { User } from '../models/User';
import { Product } from '../models/Product';
import { Order } from '../models/Order';

const esc = (v: unknown) => String(v ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

try {
  const conn = await connectDB();
  const products = await Product.find({}).sort({ sortOrder: 1 }).lean();
  const users = await User.find({}).select('+passwordHash').sort({ createdAt: -1 }).lean();
  const orders = await Order.find({}).sort({ createdAt: -1 }).lean();

  const hashes = users.map((u) => String((u as { passwordHash?: string }).passwordHash ?? ''));
  const allBcrypt = hashes.every((h) => /^\$2[aby]\$12\$[./A-Za-z0-9]{53}$/.test(h));
  console.log(`Database "${conn.connection.name}" on MongoDB Atlas`);
  console.log(`products: ${products.length} · users: ${users.length} · orders: ${orders.length}`);
  console.log(`passwordHash is a bcrypt hash (cost 12, 60 chars) for every user: ${allBcrypt ? 'YES' : 'NO'}`);
  console.log(`sample hash prefixes: ${hashes.slice(0, 3).map((h) => `${h.slice(0, 7)}… (${h.length} chars)`).join(', ') || '(no users)'}`);
  const owners = new Set(orders.map((o) => String(o.user)));
  console.log(`orders belong to ${owners.size} different user(s); every order has a user: ${orders.every((o) => o.user) ? 'YES' : 'NO'}`);

  if (process.argv.includes('--html')) {
    const row = (cells: unknown[]) => `<tr>${cells.map((c) => `<td>${esc(c)}</td>`).join('')}</tr>`;
    const html = `<!doctype html><html><head><meta charset="utf-8"><title>Live query of MongoDB Atlas — shadowgate</title>
<style>body{margin:0;background:#001e2b;color:#e8edeb;font:14px/1.45 "Segoe UI",system-ui,sans-serif}
header{display:flex;gap:14px;align-items:center;padding:14px 22px;background:#023430;border-bottom:1px solid #00684a}
header b{color:#00ed64;font-size:16px}.chip{padding:3px 10px;border:1px solid #00684a;border-radius:99px;color:#71f6ba;font-size:12px}
main{padding:18px 22px;display:grid;gap:18px}h2{margin:0 0 8px;font-size:15px;color:#00ed64;font-family:Consolas,monospace}
table{width:100%;border-collapse:collapse;background:#112733;border:1px solid #1c2d38;border-radius:8px;overflow:hidden;font-size:12.5px}
th,td{padding:7px 10px;border-bottom:1px solid #1c2d38;text-align:left;vertical-align:top}th{background:#0b3b35;color:#c3e7d9;font-weight:600}
td{font-family:Consolas,monospace;color:#e8edeb}.note{color:#889397;font-size:12px}</style></head><body>
<header><b>Live query of MongoDB Atlas</b><span class="chip">generated by scripts/db-report.ts (npm run db:report -- --html)</span><span class="chip">Project: ShadowGate</span><span class="chip">Cluster: ShadowGate (M0 Free · AWS us-east-1)</span><span class="chip">Database: ${esc(conn.connection.name)}</span><span class="chip">live query ${esc(new Date().toISOString().slice(0, 16).replace('T', ' '))} UTC</span></header>
<main>
<section><h2>shadowgate.products · ${products.length} documents</h2><table><tr><th>slug</th><th>name</th><th>category</th><th>price</th><th>pricing.kind</th><th>featured</th><th>image</th></tr>
${products.map((p) => row([p.slug, p.name, p.category, p.price, p.pricing?.kind, p.featured, p.image])).join('')}</table>
<p class="note">Quote-based services store price 0 with pricing.kind "quote" — the storefront shows “Request a quote”.</p></section>
<section><h2>shadowgate.users · ${users.length} documents</h2><table><tr><th>_id</th><th>name</th><th>email</th><th>passwordHash (bcrypt, truncated)</th><th>createdAt</th></tr>
${users.slice(0, 10).map((u, i) => row([u._id, u.name, u.email, `${hashes[i].slice(0, 29)}…`, u.createdAt?.toISOString?.().slice(0, 19)])).join('')}</table>
<p class="note">Passwords are never stored — only bcrypt hashes (cost 12). Hashes are truncated here and never returned by the API. Showing the 10 newest of ${users.length}.</p></section>
<section><h2>shadowgate.orders · ${orders.length} documents</h2><table><tr><th>_id</th><th>user (ref users)</th><th>items (slug × qty @ price)</th><th>total</th><th>status</th><th>createdAt</th></tr>
${orders.slice(0, 10).map((o) => row([o._id, o.user, (o.items ?? []).map((i) => `${i.slug} × ${i.quantity} @ ${i.price}`).join(', '), o.total, o.status, o.createdAt?.toISOString?.().slice(0, 19)])).join('')}</table><p class="note">Showing the 10 newest of ${orders.length}. Each order references its owner in users; the API only ever returns the signed-in owner's orders.</p></section>
</main></body></html>`;
    writeFileSync('db-report.html', html);
    console.log('wrote db-report.html');
  }
} finally {
  await mongoose.disconnect();
}
